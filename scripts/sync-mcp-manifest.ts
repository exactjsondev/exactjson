import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { CATALOG, PACKS, PACK_IDS, SERVICE_VERSION } from "../src/config/catalog";

export function renderMcpManifestSource(): string {
  const packRecord = Object.fromEntries(
    PACK_IDS.map((id) => [
      id,
      {
        id: PACKS[id].id,
        title: PACKS[id].title,
        disclaimer: PACKS[id].disclaimer,
        workflows: PACKS[id].workflows,
      },
    ])
  );

  const endpoints = CATALOG.map((entry) => ({
    id: entry.id,
    pack: entry.pack,
    path: entry.path,
    priceFormatted: entry.priceFormatted,
    description: entry.description,
    inputSchema: {
      properties: entry.inputSchema.properties,
      required: entry.inputSchema.required ?? [],
    },
  }));

  return [
    "// AUTO-GENERATED by scripts/sync-mcp-manifest.ts — DO NOT EDIT MANUALLY.",
    `export const SERVICE_VERSION = ${JSON.stringify(SERVICE_VERSION)};`,
    `export const PACK_IDS = ${JSON.stringify(PACK_IDS)};`,
    `export const PACKS = ${JSON.stringify(packRecord, null, 2)};`,
    `export const ENDPOINTS = ${JSON.stringify(endpoints, null, 2)};`,
    "",
  ].join("\n");
}

const isMain =
  Boolean(process.argv[1]) &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1]!);

if (isMain) {
  const outPath = resolve(process.cwd(), "mcp/catalog.generated.mjs");
  writeFileSync(outPath, renderMcpManifestSource(), "utf8");
  console.log(
    `Generated ${pathToFileURL(outPath).pathname} (${CATALOG.length} endpoints across ${PACK_IDS.length} packs).`
  );
}
